export const getAnimalById = (id: string): Animal | undefined =>
  animals.find((a) => a.id === id);

export const getAnimalsByCategory = (category: Animal['category']): Animal[] =>
  animals.filter((a) => a.category === category);

export const getDefaultUnlocked = (): Animal[] =>
  animals.filter((a) => a.isDefaultUnlocked);

export const getPuzzleAnimals = (): Animal[] =>
  animals.filter((a) => !!a.puzzleAsset);

export const getColoringAnimals = (): Animal[] =>
  animals.filter((a) => !!a.coloringAsset);
